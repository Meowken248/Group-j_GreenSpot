// Lowercase lookup map for case-insensitive matching
const LOWER_DOM_MAP: Record<string, string> = {};
for (const [vi, en] of Object.entries(DOM_TRANSLATION_MAP)) {
  LOWER_DOM_MAP[vi.toLowerCase()] = en;
}

// Inverted dictionary (EN -> VI)
const EN_TO_VI_MAP: Record<string, string> = {};
for (const [vi, en] of Object.entries(DOM_TRANSLATION_MAP)) {
  EN_TO_VI_MAP[en] = vi;
}

// Pre-sorted arrays by string length descending to guarantee greedy matching
const SORTED_DOM_MAP = Object.entries(DOM_TRANSLATION_MAP).sort(
  (a, b) => b[0].length - a[0].length
);
const SORTED_EN_TO_VI_MAP = Object.entries(EN_TO_VI_MAP).sort(
  (a, b) => b[0].length - a[0].length
);

const CACHE_STORAGE_KEY = "greenspot_i18n_cache_v2";

const loadCachedTranslations = (): Record<string, string> => {
  try {
    const raw = localStorage.getItem(CACHE_STORAGE_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
};

const saveCachedTranslations = (cache: Record<string, string>) => {
  try {
    localStorage.setItem(CACHE_STORAGE_KEY, JSON.stringify(cache));
  } catch {
    // Quota handled safely
  }
};

const asyncTranslationCache: Record<string, string> = loadCachedTranslations();
const inFlightRequests = new Set<string>();
const pendingBatchQueue = new Set<string>();
let batchDebounceTimer: ReturnType<typeof setTimeout> | null = null;
let observer: MutationObserver | null = null;
let isTranslating = false;
let activeLang: "VI" | "EN" = "VI";

function flushBatchQueue() {
  if (pendingBatchQueue.size === 0) return;
  const itemsToTranslate = Array.from(pendingBatchQueue).slice(0, 50);
  itemsToTranslate.forEach((item) => pendingBatchQueue.delete(item));

  api
    .post<{ translations: string[] }>("/api/v1/translation/batch", {
      texts: itemsToTranslate,
      target_lang: "en",
      source_lang: "vi",
    })
    .then((res) => {
      itemsToTranslate.forEach((item) => inFlightRequests.delete(item));
      const translations = res.data?.translations;
      if (Array.isArray(translations) && translations.length === itemsToTranslate.length) {
        let hasNew = false;
        itemsToTranslate.forEach((original, idx) => {
          const trans = translations[idx];
          if (trans && trans.trim()) {
            asyncTranslationCache[original] = trans.trim();
            hasNew = true;
          }
        });
        if (hasNew) {
          saveCachedTranslations(asyncTranslationCache);
          if (activeLang === "EN") {
            requestAnimationFrame(() => applyDOMTranslation(document.body, "EN"));
          }
        }
      }
    })
    .catch(() => {
      itemsToTranslate.forEach((item) => inFlightRequests.delete(item));
    });
}

function queueBatchTranslation(text: string) {
  if (inFlightRequests.has(text) || asyncTranslationCache[text]) return;
  inFlightRequests.add(text);
  pendingBatchQueue.add(text);
  if (batchDebounceTimer) clearTimeout(batchDebounceTimer);
  batchDebounceTimer = setTimeout(flushBatchQueue, 50);
}

/**
 * Standard Vietnamese Accent Remover / Romanization
 * Converts accented proper nouns into clean Latin text (e.g. "Nguyễn Văn Quá" -> "Nguyen Van Qua")
 */
export function stripVietnameseAccents(str: string): string {
  if (!str) return str;
  return str
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D");
}

/**
 * Translates a single string using exact dictionary, greedy substring replacement,
 * common regex patterns, and automatic accent romanization for proper nouns.
 */
export function translateString(text: string, targetLang: "VI" | "EN"): string {
  if (!text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  if (targetLang === "EN") {
    // 0. Extract leading and trailing emoji/icon symbols if any
    const emojiPrefixMatch = trimmed.match(/^([\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE00}-\u{FE0F}\u{1F900}-\u{1F9FF}\s📍📞🛡️👥✅➕📤⚠️📁●★•\-\+]+)/u);
    const prefix = emojiPrefixMatch ? emojiPrefixMatch[1] : "";
    const coreText = prefix ? trimmed.slice(prefix.length).trim() : trimmed;

    // 1. Exact match in dictionary
    if (DOM_TRANSLATION_MAP[trimmed]) {
      return text.replace(trimmed, DOM_TRANSLATION_MAP[trimmed]);
    }
    if (coreText && DOM_TRANSLATION_MAP[coreText]) {
      return text.replace(trimmed, prefix + DOM_TRANSLATION_MAP[coreText]);
    }

    // 2. Exact match in async cache
    if (asyncTranslationCache[trimmed]) {
      return text.replace(trimmed, asyncTranslationCache[trimmed]);
    }
    if (coreText && asyncTranslationCache[coreText]) {
      return text.replace(trimmed, prefix + asyncTranslationCache[coreText]);
    }

    // 3. Case-insensitive exact match
    const lowerTrimmed = trimmed.toLowerCase();
    if (LOWER_DOM_MAP[lowerTrimmed]) {
      const trans = LOWER_DOM_MAP[lowerTrimmed];
      const adjusted = trimmed === trimmed.toUpperCase() ? trans.toUpperCase() : trans;
      return text.replace(trimmed, adjusted);
    }
    if (coreText) {
      const lowerCore = coreText.toLowerCase();
      if (LOWER_DOM_MAP[lowerCore]) {
        const trans = LOWER_DOM_MAP[lowerCore];
        const adjusted = coreText === coreText.toUpperCase() ? trans.toUpperCase() : trans;
        return text.replace(trimmed, prefix + adjusted);
      }
    }

    let result = text;
    let replaced = false;

    // 4. GREEDY SUBSTRING REPLACEMENT (Longer phrases first, preventing broken tokens)
    for (const [vi, en] of SORTED_DOM_MAP) {
      if (vi.length >= 2 && result.includes(vi)) {
        result = result.split(vi).join(en);
        replaced = true;
      }
    }

    // 5. Regex replacements for common patterns with numbers/variables and urban terms
    const withPatterns = result
      // Relative times
      .replace(/(\d+)\s*phút\s*trước/gi, "$1 minutes ago")
      .replace(/(\d+)\s*giờ\s*trước/gi, "$1 hours ago")
      .replace(/(\d+)\s*ngày\s*trước/gi, "$1 days ago")
      .replace(/(\d+)\s*tuần\s*trước/gi, "$1 weeks ago")
      .replace(/(\d+)\s*tháng\s*trước/gi, "$1 months ago")
      // Quantities
      .replace(/(\d+)\s*người\s*dân/gi, "$1 residents")
      .replace(/(\d+)\s*người/gi, (_m, num) => (num === "1" ? "1 person" : `${num} people`))
      .replace(/(\d+)\s*trẻ\s*nhỏ/gi, (_m, num) => (num === "1" ? "1 child" : `${num} children`))
      .replace(/(\d+)\s*người\s*già/gi, "$1 elderly")
      .replace(/(\d+)\s*bạn\s*chung/gi, (_m, num) => (num === "1" ? "1 mutual friend" : `${num} mutual friends`))
      .replace(/(\d+)\s*điểm/gi, (_m, num) => (num === "1" ? "1 point" : `${num} points`))
      .replace(/(\d+)\s*vai\s*trò/gi, (_m, num) => (num === "1" ? "1 role" : `${num} roles`))
      .replace(/(\d+)\s*thiết\s*bị/gi, (_m, num) => (num === "1" ? "1 device" : `${num} devices`))
      .replace(/(\d+)\s*lệnh/gi, (_m, num) => (num === "1" ? "1 order" : `${num} orders`))
      .replace(/(\d+)\s*sự\s*cố/gi, (_m, num) => (num === "1" ? "1 incident" : `${num} incidents`))
      .replace(/(\d+)\s*phản\s*ánh/gi, (_m, num) => (num === "1" ? "1 report" : `${num} reports`))
      .replace(/(\d+)\s*điều\s*khoản/gi, "$1 clauses")
      .replace(/(\d+)\s*trạm/gi, "$1 stations")
      .replace(/(\d+)\s*bãi\s*rác/gi, "$1 dump sites")
      .replace(/Bán\s*kính\s*(\d+)km/gi, "$1km radius")
      .replace(/Cách\s*bạn\s*(\d+)m/gi, "$1m away from you")
      .replace(/sâu\s*(\d+)cm/gi, "$1cm deep")
      // Coordinates & GPS
      .replace(/Tọa\s*độ:\s*/gi, "Coordinates: ")
      .replace(/Độ\s*chính\s*xác:\s*/gi, "Accuracy: ")
      .replace(/Đã\s*định\s*vị\s*tọa\s*độ\s*GPS\s*của\s*bạn/gi, "Your GPS coordinates have been determined")
      // Address prefixes
      .replace(/\bNgã\s*tư\b/gi, "Intersection of")
      .replace(/\bGiao\s*lộ\b/gi, "Intersection of")
      .replace(/\bĐường\b/gi, "Street")
      .replace(/\bPhường\b/gi, "Ward")
      .replace(/\bQuận\b/gi, "District")
      .replace(/\bHuyện\b/gi, "District")
      .replace(/\bTP\.?\s*Thủ\s*Đức\b/gi, "Thu Duc City")
      .replace(/\bTP\.?\s*HCM\b/gi, "HCMC")
      .replace(/\bTP\.?\s*Hồ\s*Chí\s*Minh\b/gi, "HCMC")
      .replace(/\bBờ\s*kè\b/gi, "Embankment")
      .replace(/\bChợ\b/gi, "Market")
      .replace(/\bKênh\b/gi, "Canal")
      .replace(/\bSông\b/gi, "River")
      .replace(/\bCầu\b/gi, "Bridge")
      .replace(/\bHẻm\b/gi, "Alley")
      .replace(/\bĐoạn\b/gi, "Section")
      // Response teams
      .replace(/Đội\s*Cơ\s*động\s*số\s*(\d+)/gi, "Mobile Team No. $1")
      .replace(/Đội\s*Thoát\s*Nước\s*Thủ\s*Đức/gi, "Thu Duc Drainage Team")
      .replace(/Đội\s*MTĐT\s*(?:Quận|District)\s*(\d+)/gi, "Urban Environment Team District $1")
      .replace(/Đội\s*MTĐT\s*(\d+)/gi, "Urban Environment Team District $1")
      .replace(/Đội\s*Môi\s*trường\s*đô\s*thị\s*Quận\s*(\d+)/gi, "District $1 Urban Environment Team")
      .replace(/Đội\s*(?:Cứu\s*hộ\s*ngập\s*lụt|Flood\s*Rescue)\s*Bình\s*Thạnh/gi, "Binh Thanh Flood Rescue Team")
      .replace(/Đội\s*tuần\s*tra\s*môi\s*trường\s*(\d+)/gi, "Environmental Patrol Team $1")
      .replace(/Đội\s*phản\s*ứng\s*nhanh\s*(\d+)/gi, "Rapid Response Team $1")
      .replace(/Đội\s*nạo\s*vét\s*cơ\s*động\s*(\d+)/gi, "Mobile Dredging Team $1")
      .replace(/\bĐội\b/g, "Team")
      // Priorities
      .replace(/Khẩn\s*cấp\s*\/\s*Hỏa\s*tốc/gi, "Critical / Emergency / Urgent")
      .replace(/\bHỏa\s*tốc\b/gi, "Urgent")
      .replace(/\bKhẩn\s*cấp\b/gi, "Critical")
      .replace(/\bCao\b/g, "High")
      .replace(/\bTrung\s*bình\b/g, "Medium")
      .replace(/\bThấp\b/g, "Low")
      // Statuses
      .replace(/\bĐã\s*giao\s*lệnh\b/gi, "Delivered")
      .replace(/\bĐã\s*giao\b/gi, "Delivered")
      .replace(/\bĐang\s*đến\b/gi, "Coming")
      .replace(/\bĐang\s*xử\s*lý\b/gi, "In Progress")
      .replace(/\bHoàn\s*tất\b/gi, "Completed")
      .replace(/\bĐã\s*hu[yỷ]\b/gi, "Canceled")
      // Domain incident types
      .replace(/Điểm\s*ngập\s*(?:sâu|úng|nước)\b/gi, "Flood Point")
      .replace(/Ngập\s*(?:úng|lụt)\b/gi, "Flooding")
      .replace(/Bãi\s*rác\s*tự\s*phát\b/gi, "Illegal Dump Site")
      .replace(/Ùn\s*ứ\s*(?:rác\s*sinh\s*hoạt|Domestic\s*Waste)\b/gi, "Domestic waste accumulation")
      .replace(/Ùn\s*ứ\b/gi, "Accumulation")
      .replace(/Điểm\s*nghẽn\s*cống\b/gi, "Drainage blockage");

    if (withPatterns !== result) {
      result = withPatterns;
      replaced = true;
    }

    // 6. If address terms or incident terms matched, romanize proper nouns in that context
    if (replaced && /[\u00C0-\u1EF9]/i.test(result)) {
      result = stripVietnameseAccents(result);
    }

    if (replaced) {
      asyncTranslationCache[trimmed] = result.trim();
      return result;
    }

    // 7. Asynchronous high-performance batch translation for Vietnamese phrases and sentences
    if (/[\u00C0-\u1EF9]/i.test(trimmed) && trimmed.length >= 2) {
      queueBatchTranslation(trimmed);
    }

    // 8. NEVER strip accents as pseudo-translation! Return text as-is.
    return text;
  } else {
    // Reverse to VI
    if (EN_TO_VI_MAP[trimmed]) {
      return text.replace(trimmed, EN_TO_VI_MAP[trimmed]);
    }
    let result = text;
    for (const [en, vi] of SORTED_EN_TO_VI_MAP) {
      if (en.length >= 2 && result.includes(en)) {
        result = result.split(en).join(vi);
      }
    }
    return result;
  }
}

/**
 * Traverses DOM and translates text nodes, input placeholders, values, titles and aria-labels.
 * Preserves original Vietnamese on node.__orig_vi for 100% loss-free reverse restoration.
 */
export function applyDOMTranslation(root: Node = document.body, lang: "VI" | "EN") {
  if (!root || isTranslating) return;
  isTranslating = true;

  try {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === "script" || tag === "style" || tag === "noscript" || tag === "code") {
          return NodeFilter.FILTER_REJECT;
        }
        if (!node.nodeValue || !node.nodeValue.trim()) {
          return NodeFilter.FILTER_SKIP;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    });

    let currentNode = walker.nextNode();
    while (currentNode) {
      const currentVal = currentNode.nodeValue || "";
      if (lang === "EN") {
        if ((currentNode as any).__orig_vi === undefined && /[\u00C0-\u1EF9]/i.test(currentVal)) {
          (currentNode as any).__orig_vi = currentVal;
        }
        const translated = translateString(currentVal, "EN");
        if (currentVal !== translated) {
          currentNode.nodeValue = translated;
        }
      } else {
        if ((currentNode as any).__orig_vi !== undefined) {
          currentNode.nodeValue = (currentNode as any).__orig_vi;
        } else {
          const translated = translateString(currentVal, "VI");
          if (currentVal !== translated) {
            currentNode.nodeValue = translated;
          }
        }
      }
      currentNode = walker.nextNode();
    }

    if (root instanceof Element) {
      // Inputs & Textareas
      const inputs = root.querySelectorAll("input, textarea");
      inputs.forEach((el) => {
        const input = el as HTMLInputElement | HTMLTextAreaElement;
        if (input.placeholder) {
          if (lang === "EN") {
            if ((input as any).__orig_ph === undefined && /[\u00C0-\u1EF9]/i.test(input.placeholder)) {
              (input as any).__orig_ph = input.placeholder;
            }
            const trans = translateString(input.placeholder, "EN");
            if (input.placeholder !== trans) input.placeholder = trans;
          } else {
            if ((input as any).__orig_ph !== undefined) {
              input.placeholder = (input as any).__orig_ph;
            } else {
              const trans = translateString(input.placeholder, "VI");
              if (input.placeholder !== trans) input.placeholder = trans;
            }
          }
        }
        if (input.value && (input.type === "text" || input.tagName.toLowerCase() === "textarea")) {
          if (lang === "EN") {
            if ((input as any).__orig_val === undefined && /[\u00C0-\u1EF9]/i.test(input.value)) {
              (input as any).__orig_val = input.value;
            }
            const trans = translateString(input.value, "EN");
            if (input.value !== trans) input.value = trans;
          } else {
            if ((input as any).__orig_val !== undefined) {
              input.value = (input as any).__orig_val;
            } else {
              const trans = translateString(input.value, "VI");
              if (input.value !== trans) input.value = trans;
            }
          }
        }
      });

      // Tooltips & Accessibility labels
      const titledElements = root.querySelectorAll("[title], [aria-label]");
      titledElements.forEach((el) => {
        const title = el.getAttribute("title");
        if (title) {
          if (lang === "EN") {
            if ((el as any).__orig_title === undefined && /[\u00C0-\u1EF9]/i.test(title)) {
              (el as any).__orig_title = title;
            }
            const trans = translateString(title, "EN");
            if (title !== trans) el.setAttribute("title", trans);
          } else {
            if ((el as any).__orig_title !== undefined) {
              el.setAttribute("title", (el as any).__orig_title);
            } else {
              const trans = translateString(title, "VI");
              if (title !== trans) el.setAttribute("title", trans);
            }
          }
        }
        const ariaLabel = el.getAttribute("aria-label");
        if (ariaLabel) {
          if (lang === "EN") {
            if ((el as any).__orig_aria === undefined && /[\u00C0-\u1EF9]/i.test(ariaLabel)) {
              (el as any).__orig_aria = ariaLabel;
            }
            const trans = translateString(ariaLabel, "EN");
            if (ariaLabel !== trans) el.setAttribute("aria-label", trans);
          } else {
            if ((el as any).__orig_aria !== undefined) {
              el.setAttribute("aria-label", (el as any).__orig_aria);
            } else {
              const trans = translateString(ariaLabel, "VI");
              if (ariaLabel !== trans) el.setAttribute("aria-label", trans);
            }
          }
        }
      });
    }
  } finally {
    isTranslating = false;
  }
}

/**
 * Clears any external translator artifacts or cookies to ensure
 * a 100% clean, native interface without third-party bars or banners.
 */
export function clearExternalTranslatorArtifacts() {
  try {
    document.cookie = "googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;";
    if (window.location.hostname) {
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${window.location.hostname}; path=/;`;
    }
    const frames = document.querySelectorAll(
      ".goog-te-banner-frame, #google_translate_element, iframe.skiptranslate, .goog-te-gadget"
    );
    frames.forEach((el) => el.remove());
    if (document.body) {
      document.body.style.top = "0px";
    }
  } catch {
    // Ignore in SSR / test environments
  }
}


/**
 * Initializes continuous full-page observation.
 */
export function initDOMTranslation(root: Node = document.body) {
  clearExternalTranslatorArtifacts();

  if (observer) {
    observer.disconnect();
    observer = null;
  }

  const saved = localStorage.getItem("greenspot_user_lang");
  activeLang = saved === "EN" ? "EN" : "VI";

  // Bootstrap backend dictionary at launch
  syncBackendDictionary();

  if (activeLang === "EN") {
    applyDOMTranslation(root, "EN");
  }

  observer = new MutationObserver((mutations) => {
    if (isTranslating || activeLang !== "EN") return;
    for (const mut of mutations) {
      if (mut.type === "childList") {
        mut.addedNodes.forEach((node) => {
          if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) {
            applyDOMTranslation(node, "EN");
          }
        });
      } else if (mut.type === "characterData") {
        const node = mut.target;
        if (node.nodeValue && /[\u00C0-\u1EF9]/i.test(node.nodeValue)) {
          applyDOMTranslation(node.parentElement || node, "EN");
        }
      }
    }
  });

  observer.observe(root, {
    childList: true,
    subtree: true,
    characterData: true,
  });
}

/**
 * Dynamic runtime synchronization with backend dictionary
 */
export async function syncBackendDictionary() {
  try {
    const res = await api.get<Record<string, string>>("/api/v1/translation/dictionary");
    if (res.data && typeof res.data === "object") {
      Object.assign(DOM_TRANSLATION_MAP, res.data);
      for (const [vi, en] of Object.entries(res.data)) {
        LOWER_DOM_MAP[vi.toLowerCase()] = en;
        EN_TO_VI_MAP[en] = vi;
      }
      if (activeLang === "EN" && typeof document !== "undefined") {
        applyDOMTranslation(document.body, "EN");
      }
    }
  } catch {
    // Offline or test environment
  }
}

/**
 * Global API to switch whole-page language programmatically
 */
export function setGlobalPageLanguage(lang: "VI" | "EN") {
  activeLang = lang;
  clearExternalTranslatorArtifacts();
  if (typeof document !== "undefined") {
    document.documentElement.setAttribute("lang", lang.toLowerCase());
    document.documentElement.setAttribute("translate", "no");
    document.documentElement.classList.add("notranslate");
    if (document.body) {
      document.body.setAttribute("translate", "no");
      document.body.classList.add("notranslate");
      applyDOMTranslation(document.body, lang);
    }
  }
}
